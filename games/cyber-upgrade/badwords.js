// ===== ФІЛЬТР НЕЦЕНЗУРНИХ СЛІВ ДЛЯ ІМЕН =====
// Перевіряє ім'я за списком коренів. Перед перевіркою ім'я нормалізується:
// нижній регістр, прибираються пробіли й розділові знаки, цифри та символи
// замінюються на схожі літери (0→о, 3→з, 4→ч, @→а, $→s…), а латинські літери,
// схожі на кириличні, зводяться до кирилиці (і навпаки для англійських коренів).
// Список коренів можна доповнювати — кожен рядок один корінь у нижньому регістрі.
// Та сама логіка продубльована у скрипті таблиці (docs/cyber-upgrade-leaderboard.gs).
(function () {
  'use strict';

  // Корені кирилицею (укр./рос.)
  var CYR = [
    'хуй', 'хуя', 'хує', 'хуе', 'хуї', 'хуи', 'хуі', 'хуйл', 'хуіл', 'хуил',
    'пизд', 'пізд',
    'бляд', 'блят', 'бля',
    'ебал', 'ебан', 'ебат', 'ебну', 'ебло', 'ебуч',
    'їбал', 'їбан', 'їбат', 'їбну', 'йобан', 'йобн', 'йоба', 'єбал', 'єбан', 'єбат',
    'уеб', 'уёб', 'уєб',
    'сука', 'сучк', 'сучар',
    'мудак', 'мудил', 'мудо',
    'гандон', 'гондон',
    'залуп',
    'пидор', 'підор', 'пидар', 'підар', 'педик', 'пидр', 'підр',
    'жоп', 'дроч', 'шлюх', 'курв', 'срак', 'сран', 'гівн', 'говн', 'дерьм',
    'сцик', 'пердун', 'далбо', 'долбо', 'дебіл', 'дебил', 'даун', 'лох', 'чмо', 'нахуй', 'нахер'
  ];

  // Корені латиницею (англ.)
  var LAT = [
    'fuck', 'fuk', 'fck', 'shit', 'bitch', 'cunt', 'asshole', 'pussy', 'whore', 'slut',
    'nigg', 'bastard', 'porn', 'wtf', 'motherf'
  ];

  var DIGITS = { '0': 'о', '1': 'і', '3': 'з', '4': 'ч', '5': 's', '6': 'б', '9': 'я', '@': 'а', '$': 's', '!': 'і', '|': 'і' };

  // латиниця → схожа кирилиця
  var LAT2CYR = { a: 'а', b: 'в', c: 'с', e: 'е', h: 'н', i: 'і', k: 'к', m: 'м', o: 'о', p: 'р', t: 'т', x: 'х', y: 'у', u: 'и', n: 'п', r: 'г', g: 'д', w: 'ш', s: 'с', d: 'д', l: 'л', f: 'ф', v: 'в', z: 'з', j: 'й', q: 'к' };
  // кирилиця → схожа латиниця
  var CYR2LAT = { 'а': 'a', 'в': 'b', 'с': 'c', 'е': 'e', 'н': 'h', 'і': 'i', 'к': 'k', 'м': 'm', 'о': 'o', 'р': 'p', 'т': 't', 'х': 'x', 'у': 'y', 'и': 'u', 'п': 'n', 'г': 'r', 'д': 'd', 'ш': 'w', 'з': 'z', 'й': 'j', 'л': 'l', 'ф': 'f' };

  function base(name) {
    return String(name || '').toLowerCase()
      .replace(/[0-9@$!|]/g, function (ch) { return DIGITS[ch] || ''; })
      .replace(/[^a-zа-яіїєґё]/g, '')
      .replace(/ё/g, 'е');
  }

  function mapChars(str, table) {
    var out = '';
    for (var i = 0; i < str.length; i++) out += table[str[i]] || str[i];
    return out;
  }

  // Згортає повтори літер: "сууука" → "сука"
  function squeeze(str) {
    return str.replace(/(.)\1+/g, '$1');
  }

  function containsAny(str, roots) {
    for (var i = 0; i < roots.length; i++) if (str.indexOf(roots[i]) !== -1) return true;
    return false;
  }

  window.isBadName = function (name) {
    var b = base(name);
    if (!b) return false;
    var cyr = mapChars(b, LAT2CYR);
    var lat = mapChars(b, CYR2LAT);
    return containsAny(cyr, CYR) || containsAny(squeeze(cyr), CYR) ||
           containsAny(lat, LAT) || containsAny(squeeze(lat), LAT);
  };
})();
